"""Run a mouse-level observational transport audit on the official IBL BWM.

The bounded task predicts coarse Cosmos anatomy from non-anatomical unit-level
electrophysiological descriptors. Coordinates, atlas identifiers, channel,
depth, and region-derived predictors are prohibited. The classifier is fitted
only on calibration mice. Two unit folds provide authorization evidence and a
third disjoint fold provides a reference label for each insertion. IBL cannot
support directed, causal, mechanistic, or digital-twin claims in this audit.
"""

