def _file_hash(path: Path, algorithm: str) -> str:
    digest = hashlib.new(algorithm)
    with path.open("rb") as handle:
        while chunk := handle.read(8 * 1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _stable_hash(namespace: str, value: str) -> str:
    return hashlib.sha256(f"{namespace}:{value}".encode()).hexdigest()


def subject_partition_value(subject_uuid: str) -> int:
    """Return the protocol-frozen SHA-256 modulo-five mouse partition."""

    return int(hashlib.sha256(subject_uuid.encode()).hexdigest(), 16) % 5


def subject_role(subject_uuid: str) -> str:
    return (
        "calibration_context"
        if subject_partition_value(subject_uuid) in {0, 1, 2}
        else "locked_mouse_test"
    )


def deterministic_unit_folds(
    unit_ids: Sequence[str],
    *,
    namespace: str,
) -> tuple[np.ndarray, ...]:
    """Split units into balanced disjoint folds using immutable identifiers."""

    ordered = sorted(
        enumerate(map(str, unit_ids)),
        key=lambda item: _stable_hash(namespace, item[1]),
    )
    folds: list[list[int]] = [[] for _ in range(FOLD_COUNT)]
    for rank, (index, _) in enumerate(ordered):
        folds[rank % FOLD_COUNT].append(index)
    return tuple(np.asarray(fold, dtype=np.int64) for fold in folds)


def prepare_selection(
    *,
    root: Path = DEFAULT_ROOT,
    metadata_path: Path = DEFAULT_METADATA,
    output: Path = DEFAULT_SELECTION,
) -> Path:
    """Freeze the 24 outcome-independent insertion and mouse identifiers."""

    rows = json.loads(metadata_path.read_text())
    if len(rows) != MAX_INSERTIONS:
        raise ValueError(f"IBL metadata must contain exactly {MAX_INSERTIONS} insertions")
    if len({row["pid"] for row in rows}) != MAX_INSERTIONS:
        raise ValueError("IBL selection repeats a probe insertion")
    if len({row["subject_uuid"] for row in rows}) != MAX_INSERTIONS:
        raise ValueError("IBL selection must use one insertion per mouse")
    for row in rows:
        expected = subject_partition_value(str(row["subject_uuid"]))
        if int(row["subject_partition_value"]) != expected:
            raise ValueError("stored IBL subject partition disagrees with SHA-256 rule")
        if int(row["good_units"]) < MIN_GOOD_UNITS:
            raise ValueError("selected IBL insertion violates the good-unit minimum")
        if int(row["regions"]) < MIN_COSMOS_CLASSES:
            raise ValueError("selected IBL insertion violates the class minimum")

    clusters = root / CLUSTERS_FILENAME
    actual_md5 = _file_hash(clusters, "md5")
    if actual_md5 != EXPECTED_CLUSTERS_MD5:
        raise ValueError("official IBL aggregate cluster-table MD5 mismatch")
    payload = {
        "protocol": "ibl_bwm_mouse_observational_transport_v3",
        "selection_revision": code_revision(),
        "release_tag": RELEASE_TAG,
        "published_dataset_doi": DATA_DOI,
        "official_repository_revision": OFFICIAL_REPOSITORY_REVISION,
        "selection_uses_model_predictions": False,
        "selection_basis": (
            "official frozen 699-insertion fixture, at least 50 good units, at least "
            "two non-root Cosmos classes, one SHA-256-selected insertion per mouse, "
            "and 24 SHA-256-selected mouse nicknames"
        ),
        "subject_split": "sha256(subject_uuid) modulo 5; 0-2 context, 3-4 locked test",
        "maximum_insertions": MAX_INSERTIONS,
        "insertions": [
            {
                key: row[key]
                for key in (
                    "pid",
                    "eid",
                    "probe_name",
                    "subject",
                    "subject_uuid",
                    "subject_partition_value",
                    "lab",
                    "good_units",
                    "regions",
                )
            }
            for row in rows
        ],
        "partition_counts": {
            role: sum(subject_role(str(row["subject_uuid"])) == role for row in rows)
            for role in ("calibration_context", "locked_mouse_test")
        },
        "source_files": {
            CLUSTERS_FILENAME: {
                "bytes": clusters.stat().st_size,
                "md5": actual_md5,
            },
            FIXTURE_FILENAME: {
                "sha256": _file_hash(root / FIXTURE_FILENAME, "sha256")
            },
            REGION_INFO_FILENAME: {
                "sha256": _file_hash(root / REGION_INFO_FILENAME, "sha256")
            },
        },
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(payload, indent=2) + "\n")
    return output


def _signed_log1p(values: np.ndarray) -> np.ndarray:
    return np.sign(values) * np.log1p(np.abs(values))


def electrophysiology_matrix(frame: pd.DataFrame) -> np.ndarray:
    """Encode non-anatomical unit descriptors without target leakage."""

    if PROHIBITED_PREDICTORS & set(ELECTROPHYSIOLOGY_FEATURES):
        raise RuntimeError("IBL electrophysiology schema contains a prohibited predictor")
    matrix = frame.loc[:, ELECTROPHYSIOLOGY_FEATURES].apply(
        pd.to_numeric, errors="coerce"
    ).to_numpy(dtype=float)
    for column in range(matrix.shape[1]):
        matrix[:, column] = _signed_log1p(matrix[:, column])
    return matrix


def _classifier():
    from sklearn.impute import SimpleImputer
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import StandardScaler

    return Pipeline(
        (
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
            (
                "classifier",
                LogisticRegression(
                    C=1.0,
                    class_weight="balanced",
                    max_iter=2_000,
                    random_state=0,
                ),
            ),
        )
    )


def _macro_recall(observed: np.ndarray, predicted: np.ndarray) -> float:
    classes = np.unique(observed)
    return float(
        np.mean([np.mean(predicted[observed == value] == value) for value in classes])
    )


def prediction_diagnostic(
    observed: np.ndarray,
    predicted: np.ndarray,
    *,
    seed: int,
) -> dict[str, Any]:
    """Evaluate multiclass prediction against a fixed-label permutation null."""

    from sklearn.metrics import matthews_corrcoef

    observed = np.asarray(observed)
    predicted = np.asarray(predicted)
    if len(observed) != len(predicted) or len(observed) < 10:
        raise ValueError("IBL diagnostic requires at least ten paired unit predictions")
    balanced_accuracy = _macro_recall(observed, predicted)
    mcc = float(matthews_corrcoef(observed, predicted))
    rng = np.random.default_rng(seed)
    null = np.asarray(
        [_macro_recall(rng.permutation(observed), predicted) for _ in range(PERMUTATIONS)]
    )
    p_value = float((1 + np.sum(null >= balanced_accuracy)) / (PERMUTATIONS + 1))
    margin = float(balanced_accuracy - np.mean(null))
    passed = bool(
        mcc > MIN_MCC
        and margin > MIN_BALANCED_ACCURACY_MARGIN
        and p_value < PERMUTATION_ALPHA
    )
    return {
        "passed": passed,
        "balanced_accuracy": balanced_accuracy,
        "matthews_correlation": mcc,
        "permutation_p_value": p_value,
        "permutation_null_mean": float(np.mean(null)),
        "balanced_accuracy_margin": margin,
        "permutations": PERMUTATIONS,
        # The frozen score schema contains a generic correlation field. MCC is
        # a genuine multiclass correlation coefficient, while R2 is not used.
        "correlation": mcc,
        "p_value": p_value,
        "r_squared": 0.0,
    }


def _block(
    name: str,
    status: EvidenceStatus,
    rule: str,
    observations: Mapping[str, Any] | None = None,
) -> EvidenceBlock:
    return EvidenceBlock.from_mapping(
        name=name,
        status=status,
        source="official IBL Brain-Wide Map aggregate bounded adapter",
        rule=rule,
        rationale=f"the insertion-level observational rule returned `{status.value}`",
        observations=dict(observations or {}),
    )


def insertion_feature_and_label(
    *,
    insertion: Mapping[str, Any],
    first: Mapping[str, Any],
    second: Mapping[str, Any],
    reference: Mapping[str, Any],
    sample_size: int,
    claim_names: tuple[str, ...],
) -> tuple[np.ndarray, np.ndarray]:
    """Map disjoint diagnostic folds to policy features and reference labels."""

    prediction_status = (
        EvidenceStatus.PASSED if bool(first["passed"]) else EvidenceStatus.FAILED
    )
    reproduction_pass = bool(first["passed"] and second["passed"])
    reproduction_status = (
        EvidenceStatus.PASSED if reproduction_pass else EvidenceStatus.FAILED
    )
    unavailable = EvidenceStatus.NOT_APPLICABLE
    blocks = blocks_by_name(
        (
            _block(
                "prediction",
                prediction_status,
                "MCC > 0.10, balanced-accuracy margin > 0.05, permutation p < 0.01",
                first,
            ),
            _block(
                "reproducible_compute",
                EvidenceStatus.PASSED,
                "MD5-verified aggregate, frozen mice, and deterministic unit folds",
                {"pid": insertion["pid"], "subject_uuid": insertion["subject_uuid"]},
            ),
            _block(
                "internal_reproduction",
                reproduction_status,
                "the predictive rule passes in both disjoint evidence folds",
                {"first": dict(first), "second": dict(second)},
            ),
            _block(
                "external_replication",
                unavailable,
                "a multi-laboratory resource is not a new independent replication study",
            ),
            _block("topology_specificity", unavailable, "no topology is evaluated"),
            _block(
                "directed_identifiability",
                unavailable,
                "observational unit descriptors cannot identify direction",
            ),
            _block(
                "structure_function_association",
                unavailable,
                "the target is coarse anatomy, not a connectivity-function association",
            ),
            _block(
                "causal_intervention",
                unavailable,
                "the IBL insertion task is observational",
            ),
            _block(
                "whole_brain_coverage",
                unavailable,
                "brain-wide sampling does not give one entity whole-brain coverage",
            ),
            _block(
                "independent_validation",
                EvidenceStatus.PASSED,
                "IBL mice were excluded from score-model and risk-policy fitting",
            ),
            _block("entity_specificity", unavailable, "no mouse digital twin is defined"),
            _block("operational_compute", unavailable, "no digital-twin runtime is defined"),
        )
    )
    neutral_direction = {
        "forward_residual_dependence": 0.0,
        "reverse_residual_dependence": 0.0,
        "direction_margin": 0.0,
    }
    abstained_direction = {
        "method": "abstain",
        "attempted": False,
        "predicted_direction": "uncertain",
        "status": EvidenceStatus.NOT_APPLICABLE.value,
        "p_forward": 0.0,
        "p_backward": 0.0,
        "signed_margin": 0.0,
        "absolute_margin": 0.0,
    }
    true_claims = {"computationally_reproducible"}
    if bool(reference["passed"]):
        true_claims |= {"predictive", "internally_reproduced"}
    feature = encode_hybrid_features(
        blocks,
        legacy_direction=neutral_direction,
        anm=abstained_direction,
        sample_size=sample_size,
        noise_scale=0.0,
    )
    label = np.asarray([claim in true_claims for claim in claim_names], dtype=np.uint8)
    return feature, label


def _case_diagnostics(
    frame: pd.DataFrame,
    training: pd.DataFrame,
    *,
    namespace: str,
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    model = _classifier()
    train_x = electrophysiology_matrix(training)
    train_y = training["acronym"].astype(str).to_numpy()
    if len(np.unique(train_y)) < 2:
        raise ValueError("IBL training mice contain fewer than two Cosmos classes")
    model.fit(train_x, train_y)
    folds = deterministic_unit_folds(frame["uuids"].astype(str), namespace=namespace)
    diagnostics = []
    for fold_index, indices in enumerate(folds):
        observed = frame.iloc[indices]["acronym"].astype(str).to_numpy()
        predicted = model.predict(electrophysiology_matrix(frame.iloc[indices]))
        diagnostics.append(
            prediction_diagnostic(
                observed,
                predicted,
                seed=PERMUTATION_SEED + fold_index,
            )
        )
    return tuple(diagnostics)


def _bootstrap_mouse_cases(
    decisions: np.ndarray,
    labels: np.ndarray,
) -> dict[str, Any]:
    rng = np.random.default_rng(BOOTSTRAP_SEED)
    coverage = np.empty(BOOTSTRAP_REPLICATES, dtype=float)
    sfar = np.empty(BOOTSTRAP_REPLICATES, dtype=float)
    for replicate in range(BOOTSTRAP_REPLICATES):
        indices = rng.integers(0, len(decisions), size=len(decisions))
        metrics = semantic_false_authorization_metrics(decisions[indices], labels[indices])
        coverage[replicate] = metrics["supported_coverage"]
        sfar[replicate] = metrics["semantic_false_authorization_risk"]
    return {
        "unit": "mouse",
        "replicates": BOOTSTRAP_REPLICATES,
        "seed": BOOTSTRAP_SEED,
        "coverage_interval_95": np.quantile(coverage, [0.025, 0.975]).tolist(),
        "sfar_interval_95": np.quantile(sfar, [0.025, 0.975]).tolist(),
        "limitation": "only seven mice are in the locked partition",
    }


def run(
    *,
    root: Path = DEFAULT_ROOT,
    selection_path: Path = DEFAULT_SELECTION,
    score_model_path: Path = DEFAULT_SCORE_MODEL,
    risk_policy_path: Path = DEFAULT_RISK_POLICY,
    output: Path = DEFAULT_OUTPUT,
    markdown: Path = DEFAULT_MARKDOWN,
) -> Path:
    """Fit on calibration mice and audit frozen claim authorization by insertion."""

    selection = json.loads(selection_path.read_text())
    insertions = selection["insertions"]
    selected_pids = {str(row["pid"]) for row in insertions}
    columns = [
        "pid",
        "uuids",
        "label",
        "acronym",
        *ELECTROPHYSIOLOGY_FEATURES,
    ]
    clusters = pd.read_parquet(root / CLUSTERS_FILENAME, columns=columns)
    clusters = clusters[
        clusters["pid"].astype(str).isin(selected_pids)
        & (clusters["label"] >= 1.0)
        & ~clusters["acronym"].isin(("root", "void"))
    ].copy()
    insertion_index = {str(row["pid"]): row for row in insertions}
    clusters["subject_uuid"] = clusters["pid"].astype(str).map(
        lambda pid: str(insertion_index[pid]["subject_uuid"])
    )
    clusters["role"] = clusters["subject_uuid"].map(subject_role)

    score_model = json.loads(score_model_path.read_text())
    frozen_policy = json.loads(risk_policy_path.read_text())
    risk_policy = SemanticRiskPolicy.from_dict(frozen_policy["semantic_policy"])
    variable_claims = tuple(frozen_policy["variable_claims"])
    claim_names = tuple(score_model["claim_names"])
    calibration = clusters[clusters["role"] == "calibration_context"]
    features: list[np.ndarray] = []
    labels: list[np.ndarray] = []
    roles: list[str] = []
    case_rows: list[dict[str, Any]] = []
    for insertion in insertions:
        pid = str(insertion["pid"])
        subject_uuid = str(insertion["subject_uuid"])
        role = subject_role(subject_uuid)
        case = clusters[clusters["pid"].astype(str) == pid]
        training = calibration[calibration["subject_uuid"] != subject_uuid]
        first, second, reference = _case_diagnostics(
            case,
            training,
            namespace=f"ibl-v3:{pid}",
        )
        feature, label = insertion_feature_and_label(
            insertion=insertion,
            first=first,
            second=second,
            reference=reference,
            sample_size=min(len(fold) for fold in deterministic_unit_folds(
                case["uuids"].astype(str), namespace=f"ibl-v3:{pid}"
            )),
            claim_names=claim_names,
        )
        features.append(feature)
        labels.append(label)
        roles.append(role)
        case_rows.append(
            {
                "pid": pid,
                "subject_uuid": subject_uuid,
                "role": role,
                "units": len(case),
                "cosmos_classes": int(case["acronym"].nunique()),
                "evidence_first": first,
                "evidence_second": second,
                "reference": reference,
                "reference_used_as_policy_input": False,
            }
        )

    feature_matrix = np.vstack(features)
    label_matrix = np.vstack(labels).astype(bool)
    probabilities = predict_probabilities(
        score_model["model_sets"]["full"], feature_matrix, claim_names
    )
    requirements = {
        item.claim: item.required_blocks for item in load_default_profile().requirements
    }
    admissible = semantic_admissibility_matrix(
        feature_matrix,
        claim_names=claim_names,
        feature_names=score_model["feature_names"],
        support_vetoes=requirements,
    )
    variable_indices = np.asarray([claim_names.index(claim) for claim in variable_claims])
    decisions = authorize_with_policy(
        risk_policy,
        probabilities[:, variable_indices],
        admissible[:, variable_indices],
    )
    truths = label_matrix[:, variable_indices]
    role_array = np.asarray(roles)
    partitions = []
    for role in ("calibration_context", "locked_mouse_test"):
        indices = np.flatnonzero(role_array == role)
        metrics = semantic_false_authorization_metrics(decisions[indices], truths[indices])
        partitions.append(
            {
                "role": role,
                "mice": len(indices),
                **metrics,
                "by_claim": {
                    claim: semantic_false_authorization_metrics(
                        decisions[np.ix_(indices, [claim_index])],
                        truths[np.ix_(indices, [claim_index])],
                    )
                    for claim_index, claim in enumerate(variable_claims)
                },
                "semantic_support_violations": int(
                    (
                        (decisions[indices] == 1)
                        & ~admissible[indices][:, variable_indices]
                    ).sum()
                ),
                "mouse_bootstrap": _bootstrap_mouse_cases(
                    decisions[indices], truths[indices]
                ),
                "guarantee_transport_valid": False,
            }
        )
    locked = next(row for row in partitions if row["role"] == "locked_mouse_test")
    payload = {
        "version": __version__,
        "git_revision": code_revision(),
        "analysis": "ibl_bwm_mouse_observational_transport_audit_v3",
        "release_tag": RELEASE_TAG,
        "published_dataset_doi": DATA_DOI,
        "official_repository_revision": OFFICIAL_REPOSITORY_REVISION,
        "one_api_version": importlib.metadata.version("ONE-api"),
        "selection_sha256": _file_hash(selection_path, "sha256"),
        "aggregate_clusters_md5": _file_hash(root / CLUSTERS_FILENAME, "md5"),
        "predictive_task": "Cosmos-region classification from non-anatomical unit descriptors",
        "predictors": list(ELECTROPHYSIOLOGY_FEATURES),
        "prohibited_predictors": sorted(PROHIBITED_PREDICTORS),
        "anatomical_predictor_leakage": False,
        "insertions": len(insertions),
        "unique_mice": len({row["subject_uuid"] for row in insertions}),
        "variable_claims": list(variable_claims),
        "score_model_refitted": False,
        "risk_policy_recalibrated": False,
        "synthetic_guarantee_transported": False,
        "case_diagnostics": case_rows,
        "partitions": partitions,
        "locked_test_zero_semantic_violations": locked["semantic_support_violations"] == 0,
        "decision": (
            "ibl_observational_transport_completed_without_semantic_violation"
            if locked["semantic_support_violations"] == 0
            else "ibl_observational_transport_semantic_failure"
        ),
        "limits": [
            "The locked partition has seven mice and cannot establish a universal transport guarantee.",
            "Units within an insertion are dependent despite disjoint unit folds.",
            "Cosmos anatomy is a coarse target and does not validate behavior or a digital twin.",
            "Multi-laboratory acquisition is not treated as independent external replication.",
            "The observational task cannot authorize topology, direction, mechanism, or causality.",
        ],
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(payload, indent=2) + "\n")
    _write_markdown(payload, markdown)
    return output


def _write_markdown(payload: Mapping[str, Any], path: Path) -> None:
    lines = [
        "# IBL mouse-level observational transport audit",
        "",
        f"- Decision: `{payload['decision']}`",
        f"- Insertions / unique mice: `{payload['insertions']}` / `{payload['unique_mice']}`",
        "- Anatomical predictor leakage: `false`",
        "- Synthetic finite-sample guarantee transported: `false`",
        "",
        "| Partition | Mice | Authorizations | Coverage | SFAR | Semantic violations |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for row in payload["partitions"]:
        lines.append(
            f"| `{row['role']}` | {row['mice']} | {row['authorizations']} | "
            f"{row['supported_coverage']:.4f} | "
            f"{row['semantic_false_authorization_risk']:.4f} | "
            f"{row['semantic_support_violations']} |"
        )
    lines.extend(("", "## Limits", ""))
    lines.extend(f"- {limit}" for limit in payload["limits"])
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--metadata", type=Path, default=DEFAULT_METADATA)
    parser.add_argument("--selection", type=Path, default=DEFAULT_SELECTION)
    parser.add_argument("--score-model", type=Path, default=DEFAULT_SCORE_MODEL)
    parser.add_argument("--risk-policy", type=Path, default=DEFAULT_RISK_POLICY)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--markdown", type=Path, default=DEFAULT_MARKDOWN)
    parser.add_argument("--prepare-selection", action="store_true")
    args = parser.parse_args()
    if args.prepare_selection:
        path = prepare_selection(
            root=args.root,
            metadata_path=args.metadata,
            output=args.selection,
        )
    else:
        path = run(
            root=args.root,
            selection_path=args.selection,
            score_model_path=args.score_model,
            risk_policy_path=args.risk_policy,
            output=args.output,
            markdown=args.markdown,
        )
    print(json.dumps({"output": str(path.resolve())}))


