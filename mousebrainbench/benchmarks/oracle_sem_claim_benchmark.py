"""Oracle structural-equation benchmark for claim-contract evaluation.

The data-generating regimes define the reference graph and intervention
availability before any evidence rule is executed.  The evaluator then receives
only finite-sample diagnostics.  Consequently, reference labels are not
generated by the numerical thresholds used to assign evidence-block statuses.

This benchmark is intentionally modest.  It tests a small set of known causal
regimes and does not claim to represent the complexity of mouse-brain data.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
from scipy import stats

from mousebrainbench import __version__
from mousebrainbench.artifacts import code_revision
from mousebrainbench.validation.evidence_contract import (
    CLAIM_REQUIREMENTS_V3,
    DecisionStatus,
    EvidenceBlock,
    EvidenceContractEvaluator,
    EvidenceStatus,
    blocks_by_name,
)


DEFAULT_OUTPUT = Path("results/oracle_sem_claim_benchmark/summary.json")
DEFAULT_MARKDOWN = Path("results/oracle_sem_claim_benchmark/summary.md")

REGIMES = (
    "independent",
    "common_cause",
    "direct_x_to_y",
    "reverse_y_to_x",
    "direct_x_to_y_interventional",
)


@dataclass(frozen=True)
class GeneratedCohort:
    """Observed variables from one generated cohort."""

    x: np.ndarray
    y: np.ndarray
    controls: np.ndarray


def _generate_cohort(regime: str, n: int, rng: np.random.Generator) -> GeneratedCohort:
    """Generate one cohort from a declared structural-equation regime."""

    z = rng.laplace(size=n)
    u = rng.normal(size=(n, 3))
    ex = rng.normal(scale=0.65, size=n)
    ey = rng.normal(scale=0.65, size=n)

    if regime == "independent":
        x = rng.laplace(size=n)
        y = rng.laplace(size=n)
        controls = u
    elif regime == "common_cause":
        x = 0.80 * z + ex
        y = 1.15 * z + ey
        controls = np.column_stack((z, u[:, :2]))
    elif regime in {"direct_x_to_y", "direct_x_to_y_interventional"}:
        x = rng.laplace(size=n)
        y = 0.85 * x + 0.30 * np.square(x) + ey
        controls = u
    elif regime == "reverse_y_to_x":
        y = rng.laplace(size=n)
        x = 0.85 * y + 0.30 * np.square(y) + ex
        controls = u
    else:
        raise ValueError(f"unknown structural-equation regime: {regime}")
    return GeneratedCohort(x=x, y=y, controls=np.asarray(controls, dtype=float))


def _polynomial_design(values: np.ndarray) -> np.ndarray:
    return np.column_stack((np.ones(len(values)), values, np.square(values), np.power(values, 3)))


def _fit_predict(train_x: np.ndarray, train_y: np.ndarray, test_x: np.ndarray) -> np.ndarray:
    coefficients = np.linalg.lstsq(_polynomial_design(train_x), train_y, rcond=None)[0]
    return _polynomial_design(test_x) @ coefficients


def _r_squared(observed: np.ndarray, predicted: np.ndarray) -> float:
    denominator = float(np.sum(np.square(observed - np.mean(observed))))
    if denominator <= 0.0:
        return 0.0
    return 1.0 - float(np.sum(np.square(observed - predicted))) / denominator


def _prediction_diagnostic(train: GeneratedCohort, test: GeneratedCohort) -> dict[str, Any]:
    prediction = _fit_predict(train.x, train.y, test.x)
    correlation, p_value = stats.pearsonr(test.y, prediction)
    r_squared = _r_squared(test.y, prediction)
    passed = bool(np.isfinite(correlation) and correlation > 0.10 and p_value < 0.01 and r_squared > 0.0)
    return {
        "passed": passed,
        "correlation": float(correlation),
        "p_value": float(p_value),
        "r_squared": float(r_squared),
    }


def _topology_diagnostic(train: GeneratedCohort, test: GeneratedCohort) -> dict[str, Any]:
    candidate_r2 = _r_squared(test.y, _fit_predict(train.x, train.y, test.x))
    control_r2 = []
    for index in range(train.controls.shape[1]):
        predicted = _fit_predict(
            train.controls[:, index],
            train.y,
            test.controls[:, index],
        )
        control_r2.append(_r_squared(test.y, predicted))
    best_control = max(control_r2)
    margin = candidate_r2 - best_control
    return {
        "passed": bool(candidate_r2 > 0.0 and margin > 0.02),
        "candidate_r_squared": float(candidate_r2),
        "control_r_squared": [float(value) for value in control_r2],
        "best_control_margin": float(margin),
    }


def _residual_dependence(cause: np.ndarray, effect: np.ndarray) -> float:
    predicted = _fit_predict(cause, effect, cause)
    residual = effect - predicted
    squared_residual = np.square(residual)
    features = (cause, np.square(cause), np.abs(cause), np.sin(cause))
    values = []
    for feature in features:
        correlation = stats.spearmanr(squared_residual, feature).statistic
        values.append(abs(float(correlation)) if np.isfinite(correlation) else 1.0)
    return max(values)


def _direction_diagnostic(cohort: GeneratedCohort) -> dict[str, Any]:
    forward = _residual_dependence(cohort.x, cohort.y)
    reverse = _residual_dependence(cohort.y, cohort.x)
    margin = reverse - forward
    return {
        "passed": bool(margin > 0.02),
        "forward_residual_dependence": float(forward),
        "reverse_residual_dependence": float(reverse),
        "direction_margin": float(margin),
    }


def _causal_diagnostic(regime: str, n: int, rng: np.random.Generator) -> dict[str, Any]:
    if regime != "direct_x_to_y_interventional":
        return {"available": False, "passed": False}
    noise_plus = rng.normal(scale=0.65, size=n)
    noise_minus = rng.normal(scale=0.65, size=n)
    y_plus = 0.85 + 0.30 + noise_plus
    y_minus = -0.85 + 0.30 + noise_minus
    test = stats.ttest_ind(y_plus, y_minus, equal_var=False)
    effect = float(np.mean(y_plus) - np.mean(y_minus))
    return {
        "available": True,
        "passed": bool(effect > 0.0 and test.pvalue < 0.01),
        "mean_do_plus_minus_do_minus": effect,
        "p_value": float(test.pvalue),
    }


def _evidence_block(
    name: str,
    status: EvidenceStatus,
    rule: str,
    observations: dict[str, Any],
) -> EvidenceBlock:
    return EvidenceBlock.from_mapping(
        name=name,
        status=status,
        source="generated structural-equation observations",
        rule=rule,
        rationale=f"the generated diagnostic was assigned `{status.value}`",
        observations=observations,
    )


def _build_blocks(regime: str, seed: int, n: int) -> tuple[EvidenceBlock, ...]:
    seed_sequence = np.random.SeedSequence(seed)
    rng_train, rng_test, rng_rep, rng_intervention = [
        np.random.default_rng(child) for child in seed_sequence.spawn(4)
    ]
    train = _generate_cohort(regime, n, rng_train)
    test = _generate_cohort(regime, n, rng_test)
    reproduction = _generate_cohort(regime, n, rng_rep)

    prediction_a = _prediction_diagnostic(train, test)
    prediction_b = _prediction_diagnostic(test, reproduction)
    topology = _topology_diagnostic(train, test)
    direction = _direction_diagnostic(test)
    causal = _causal_diagnostic(regime, n, rng_intervention)

    causal_status = (
        EvidenceStatus.PASSED
        if causal["available"] and causal["passed"]
        else EvidenceStatus.FAILED
        if causal["available"]
        else EvidenceStatus.NOT_APPLICABLE
    )
    return (
        _evidence_block(
            "prediction",
            EvidenceStatus.PASSED if prediction_a["passed"] else EvidenceStatus.FAILED,
            "held-out correlation > 0.10, p < 0.01, and R-squared > 0",
            prediction_a,
        ),
        _evidence_block(
            "reproducible_compute",
            EvidenceStatus.PASSED,
            "the case is regenerated from a recorded deterministic seed",
            {"seed": seed, "n_per_cohort": n},
        ),
        _evidence_block(
            "internal_reproduction",
            EvidenceStatus.PASSED if prediction_a["passed"] and prediction_b["passed"] else EvidenceStatus.FAILED,
            "the predictive diagnostic must pass in two independently generated cohorts",
            {"first": prediction_a, "second": prediction_b},
        ),
        _evidence_block(
            "external_replication",
            EvidenceStatus.NOT_APPLICABLE,
            "no external empirical resource exists in a generated benchmark",
            {},
        ),
        _evidence_block(
            "topology_specificity",
            EvidenceStatus.PASSED if topology["passed"] else EvidenceStatus.FAILED,
            "candidate held-out R-squared must exceed every control by more than 0.02",
            topology,
        ),
        _evidence_block(
            "directed_identifiability",
            EvidenceStatus.PASSED if direction["passed"] else EvidenceStatus.FAILED,
            "reverse-minus-forward residual-dependence margin must exceed 0.02",
            direction,
        ),
        _evidence_block(
            "structure_function_association",
            EvidenceStatus.NOT_APPLICABLE,
            "the generated variables are not a synaptic structure-function dataset",
            {},
        ),
        _evidence_block(
            "causal_intervention",
            causal_status,
            "an available do(X) contrast must be positive with Welch p < 0.01",
            causal,
        ),
        _evidence_block(
            "whole_brain_coverage",
            EvidenceStatus.FAILED,
            "a five-regime scalar benchmark cannot provide whole-brain coverage",
            {},
        ),
        _evidence_block(
            "independent_validation",
            EvidenceStatus.FAILED,
            "generated cohorts are not an independent empirical validation study",
            {},
        ),
    )


def _oracle_claims(regime: str) -> set[str]:
    """Return reference claims from the DGP and evidence availability only."""

    claims = {"computationally_reproducible"}
    if regime != "independent":
        claims.update({"predictive", "internally_reproduced"})
    if regime in {"direct_x_to_y", "reverse_y_to_x", "direct_x_to_y_interventional"}:
        claims.add("topology_specific")
    if regime in {"direct_x_to_y", "direct_x_to_y_interventional"}:
        claims.add("directed")
        claims.add("mechanistic")
    if regime == "direct_x_to_y_interventional":
        claims.add("causal")
    return claims


def _prediction_shortcut(blocks: dict[str, EvidenceBlock]) -> set[str]:
    if blocks["prediction"].status is not EvidenceStatus.PASSED:
        return {"computationally_reproducible"}
    return {
        "predictive",
        "computationally_reproducible",
        "internally_reproduced",
        "topology_specific",
        "directed",
        "mechanistic",
        "causal",
    }


def _confusion(reference: set[str], predicted: set[str], universe: tuple[str, ...]) -> dict[str, int]:
    return {
        "tp": len(reference & predicted),
        "fp": len(predicted - reference),
        "tn": len(set(universe) - reference - predicted),
        "fn": len(reference - predicted),
    }


def _wilson_interval(successes: int, total: int, confidence: float = 0.95) -> list[float]:
    """Return a Wilson score interval for one binomial error rate."""

    if total <= 0:
        return [0.0, 0.0]
    z = float(stats.norm.ppf(0.5 + confidence / 2.0))
    proportion = successes / total
    denominator = 1.0 + np.square(z) / total
    centre = (proportion + np.square(z) / (2.0 * total)) / denominator
    radius = (
        z
        * np.sqrt(
            proportion * (1.0 - proportion) / total
            + np.square(z) / (4.0 * np.square(total))
        )
        / denominator
    )
    return [float(max(0.0, centre - radius)), float(min(1.0, centre + radius))]


def run(
    output: Path = DEFAULT_OUTPUT,
    markdown: Path = DEFAULT_MARKDOWN,
    *,
    seeds: int = 100,
    n_per_cohort: int = 600,
) -> Path:
    """Run finite-sample oracle cases and compare two decision policies."""

    evaluator = EvidenceContractEvaluator()
    claim_universe = tuple(requirement.claim for requirement in CLAIM_REQUIREMENTS_V3)
    aggregate = {
        "evidence_contract_v3": {"tp": 0, "fp": 0, "tn": 0, "fn": 0},
        "prediction_shortcut": {"tp": 0, "fp": 0, "tn": 0, "fn": 0},
    }
    per_claim = {
        policy: {
            claim: {"tp": 0, "fp": 0, "tn": 0, "fn": 0}
            for claim in claim_universe
        }
        for policy in aggregate
    }
    paired_correctness = {
        "both_correct": 0,
        "contract_only_correct": 0,
        "shortcut_only_correct": 0,
        "both_wrong": 0,
    }
    regime_rows: list[dict[str, Any]] = []
    for regime_index, regime in enumerate(REGIMES):
        regime_aggregate = {name: {"tp": 0, "fp": 0, "tn": 0, "fn": 0} for name in aggregate}
        for seed in range(seeds):
            case_seed = 100_000 * regime_index + seed
            indexed = blocks_by_name(_build_blocks(regime, case_seed, n_per_cohort))
            reference = _oracle_claims(regime)
            contract_claims = {
                decision.claim
                for decision in evaluator.evaluate_all(indexed)
                if decision.status is DecisionStatus.SUPPORTED
            }
            predictions = {
                "evidence_contract_v3": contract_claims,
                "prediction_shortcut": _prediction_shortcut(indexed),
            }
            for name, predicted in predictions.items():
                row = _confusion(reference, predicted, claim_universe)
                for metric, value in row.items():
                    aggregate[name][metric] += value
                    regime_aggregate[name][metric] += value
                for claim in claim_universe:
                    expected = claim in reference
                    authorized = claim in predicted
                    metric = (
                        "tp"
                        if expected and authorized
                        else "fp"
                        if not expected and authorized
                        else "fn"
                        if expected
                        else "tn"
                    )
                    per_claim[name][claim][metric] += 1
            for claim in claim_universe:
                expected = claim in reference
                contract_correct = (claim in contract_claims) == expected
                shortcut_correct = (claim in predictions["prediction_shortcut"]) == expected
                paired_key = (
                    "both_correct"
                    if contract_correct and shortcut_correct
                    else "contract_only_correct"
                    if contract_correct
                    else "shortcut_only_correct"
                    if shortcut_correct
                    else "both_wrong"
                )
                paired_correctness[paired_key] += 1
        regime_rows.append(
            {
                "regime": regime,
                "oracle_claims": sorted(_oracle_claims(regime)),
                "policies": regime_aggregate,
            }
        )

    aggregate_rows = []
    for policy, row in aggregate.items():
        fpr = row["fp"] / (row["fp"] + row["tn"]) if row["fp"] + row["tn"] else 0.0
        fnr = row["fn"] / (row["fn"] + row["tp"]) if row["fn"] + row["tp"] else 0.0
        aggregate_rows.append(
            {
                "policy": policy,
                **row,
                "false_positive_rate": fpr,
                "false_positive_rate_wilson_95": _wilson_interval(
                    row["fp"], row["fp"] + row["tn"]
                ),
                "false_negative_rate": fnr,
                "false_negative_rate_wilson_95": _wilson_interval(
                    row["fn"], row["fn"] + row["tp"]
                ),
            }
        )

    per_claim_rows = []
    for policy, claims in per_claim.items():
        for claim, row in claims.items():
            per_claim_rows.append(
                {
                    "policy": policy,
                    "claim": claim,
                    **row,
                    "false_positive_rate": (
                        row["fp"] / (row["fp"] + row["tn"])
                        if row["fp"] + row["tn"]
                        else 0.0
                    ),
                    "false_negative_rate": (
                        row["fn"] / (row["fn"] + row["tp"])
                        if row["fn"] + row["tp"]
                        else 0.0
                    ),
                }
            )

    discordant = paired_correctness["contract_only_correct"] + paired_correctness[
        "shortcut_only_correct"
    ]
    mcnemar_p = (
        float(
            stats.binomtest(
                paired_correctness["contract_only_correct"],
                discordant,
                p=0.5,
                alternative="two-sided",
            ).pvalue
        )
        if discordant
        else 1.0
    )

    contract = next(row for row in aggregate_rows if row["policy"] == "evidence_contract_v3")
    shortcut = next(row for row in aggregate_rows if row["policy"] == "prediction_shortcut")
    payload = {
        "version": __version__,
        "git_revision": code_revision(),
        "analysis": "oracle_structural_equation_claim_benchmark",
        "reference_label_source": "declared structural equations and intervention availability",
        "evidence_rule_source": "finite-sample diagnostics independent of oracle label generation",
        "regimes": list(REGIMES),
        "seeds_per_regime": seeds,
        "n_per_cohort": n_per_cohort,
        "num_cases": seeds * len(REGIMES),
        "num_claim_decisions_per_policy": seeds * len(REGIMES) * len(claim_universe),
        "aggregate_by_policy": aggregate_rows,
        "aggregate_by_policy_and_claim": per_claim_rows,
        "paired_policy_comparison": {
            **paired_correctness,
            "discordant_decisions": discordant,
            "exact_mcnemar_p_value": mcnemar_p,
        },
        "by_regime": regime_rows,
        "limits": [
            "The benchmark uses low-dimensional structural equations, not biological neural dynamics.",
            "Thresholds are prespecified operational diagnostics and are not universal scientific constants.",
            "The benchmark evaluates claim authorization under finite samples; it does not validate mouse-brain mechanisms.",
        ],
        "decision": (
            "oracle_benchmark_supports_non_compensatory_contract_with_finite_sample_errors"
            if contract["false_positive_rate"] < shortcut["false_positive_rate"]
            else "oracle_benchmark_does_not_separate_contract_from_shortcut"
        ),
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(payload, indent=2))
    write_markdown(payload, markdown)
    return output


def write_markdown(payload: dict[str, Any], markdown: Path) -> None:
    lines = [
        "# Oracle Structural-Equation Claim Benchmark",
        "",
        f"- Decision: `{payload['decision']}`",
        f"- Cases: `{payload['num_cases']}`",
        f"- Claim decisions per policy: `{payload['num_claim_decisions_per_policy']}`",
        "",
        "| Policy | TP | FP | TN | FN | FPR | FNR |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in payload["aggregate_by_policy"]:
        lines.append(
            f"| `{row['policy']}` | {row['tp']} | {row['fp']} | {row['tn']} | {row['fn']} | "
            f"{row['false_positive_rate']:.3f} | {row['false_negative_rate']:.3f} |"
        )
    lines.extend(["", "## Limits", ""])
    lines.extend(f"- {limit}" for limit in payload["limits"])
    lines.append("")
    markdown.parent.mkdir(parents=True, exist_ok=True)
    markdown.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--markdown", type=Path, default=DEFAULT_MARKDOWN)
    parser.add_argument("--seeds", type=int, default=100)
    parser.add_argument("--n-per-cohort", type=int, default=600)
    args = parser.parse_args()
    print(
        json.dumps(
            {
                "output": str(
                    run(
                        args.output,
                        args.markdown,
                        seeds=args.seeds,
                        n_per_cohort=args.n_per_cohort,
                    ).resolve()
                )
            }
        )
    )


if __name__ == "__main__":
    main()
